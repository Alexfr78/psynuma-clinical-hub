export function dasTScore(scale: DASScale, norm: DASNorm, raw: number): number | null {
  const row = DAS_NORMS[scale][norm].find(([, min, max]) => raw >= min && raw <= max);
  return row ? row[0] : null;
}

// En el DAS una T baja indica peor ajuste. Se marca como alerta una T general
// por debajo de 40 (más de una desviación típica bajo la media).
export const DAS_LOW_T = 40;

export interface DASResult {
  factorScores: Record<string, number>;
  flags: Record<string, boolean>;
}

export function scoreDAS(answers: Record<string, unknown>): DASResult {
  const factorScores: Record<string, number> = {};
  const flags: Record<string, boolean> = {};

  let total = 0;
  for (const [scale, items] of Object.entries(DAS_SCALE_ITEMS)) {
    let sum = 0;
    for (const index of items) {
      const raw = answers[index] ?? answers[String(index)];
      const value = typeof raw === 'number' ? raw : parseInt(raw as string, 10);
      if (!isNaN(value)) sum += value;
    }
    factorScores[scale] = sum;
    total += sum;
  }
  factorScores['TOTAL'] = total;

  for (const scale of ['CON', 'SAT', 'EXP', 'COH', 'TOTAL'] as DASScale[]) {
    const raw = factorScores[scale];
    const tGen = dasTScore(scale, 'GEN', raw);
    const tClin = dasTScore(scale, 'CLIN', raw);
    if (tGen !== null) factorScores[`${scale}_T_GEN`] = tGen;
    if (tClin !== null) factorScores[`${scale}_T_CLIN`] = tClin;
    if (tGen !== null && tGen < DAS_LOW_T) flags[`${scale}_low`] = true;
  }

  return { factorScores, flags };
}
